package edts.apm.android.sdk.core

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable

/**
 * Top-level ingest payload — §2 of docs/01-Kontrak-Data-API.md.
 * One request = one envelope. Static context at envelope level; volatile context per event.
 *
 * Wire shape must match iOS exactly: same field names, same schema_version.
 * sdk.name = [SdkIdentity.NAME] = "apm-android-sdk" (platform-specific; iOS uses "apmkit-ios").
 *
 * NOTE: user_id is transported RAW over TLS. Hashing to user_ref is the backend's job (BE-21).
 * The SDK must never hash it client-side. (SEC-06, CONSTITUTION invariant)
 */
@Serializable
internal data class Envelope(
    @SerialName("schema_version") val schemaVersion: Int = 1,
    val sdk: SdkInfo,
    val app: AppInfo,
    val device: DeviceInfo,
    val integrity: IntegrityInfo,
    @SerialName("install_id") val installId: String,
    @SerialName("session_id") val sessionId: String,
    @SerialName("user_id") val userId: String,
    @SerialName("user_id_source") val userIdSource: UserIdSource,
    val events: List<Event>
)

@Serializable
internal data class SdkInfo(
    val name: String,
    val version: String,
    val health: SdkHealthSnapshot
)

@Serializable
internal data class AppInfo(
    val id: String,
    val version: String,
    val build: String
)

@Serializable
internal data class DeviceInfo(
    val os: String = "Android",
    @SerialName("os_version") val osVersion: String,
    val model: String,
    val locale: String,
    val timezone: String
)

/** Integrity signals — snapshot once per session (MOB-29/30/31). Heuristics, not security gate. */
@Serializable
internal data class IntegrityInfo(
    @SerialName("is_emulator") val isEmulator: Boolean = false,
    @SerialName("is_rooted") val isRooted: Boolean = false,
    @SerialName("is_dev_mode") val isDevMode: Boolean = false,
    @SerialName("debugger_attached") val debuggerAttached: Boolean = false
)

/**
 * Whether user_id came from the host app (setUser) or was auto-generated by the SDK.
 * Wire values must be lowercase to match iOS. (§2.2)
 */
@Serializable
internal enum class UserIdSource {
    @SerialName("host") HOST,
    @SerialName("generated") GENERATED
}
